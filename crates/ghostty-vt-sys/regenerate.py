#!/usr/bin/env python3
"""Maintainer-only: regenerate with bindgen-cli 0.72.1 from pinned headers."""
import pathlib
import re
import subprocess

root = pathlib.Path(__file__).resolve().parent
subprocess.run([
    "bindgen", "include/ghostty/vt.h",
    "--allowlist-type", "Ghostty.*", "--allowlist-function", "ghostty_.*",
    "--allowlist-var", "GHOSTTY_.*", "--no-prepend-enum-name",
    "--with-derive-default", "--no-layout-tests", "--no-doc-comments",
    "--rust-target", "1.85", "--output", "src/bindings.rs",
    "--", "-std=c11", "-Iinclude",
], cwd=root, check=True)

# bindgen cannot emit these three C inline helpers or macros with C type casts
# and function calls. Keep their translations beside the generated declarations.
helpers = '''// Generated by regenerate.py from libghostty-vt 1.0.1 modes.h/style.h.
pub const fn ghostty_mode_new(value: u16, ansi: bool) -> GhosttyMode {
    (value & 0x7fff) | ((ansi as u16) << 15)
}
pub const fn ghostty_mode_value(mode: GhosttyMode) -> u16 { mode & 0x7fff }
pub const fn ghostty_mode_ansi(mode: GhosttyMode) -> bool { (mode >> 15) != 0 }
'''
modes = (root / "include/ghostty/vt/modes.h").read_text()
for name, number, ansi in re.findall(r"#define (GHOSTTY_MODE_\w+)\s+\(ghostty_mode_new\((\d+), (true|false)\)\)", modes):
    helpers += f"pub const {name}: GhosttyMode = ghostty_mode_new({number}, {ansi});\n"
styles = (root / "include/ghostty/vt/style.h").read_text()
for name, bit in re.findall(r"#define (GHOSTTY_STYLE_FLAG_\w+) \(\(GhosttyStyleFlags\)\(1u << (\d+)\)\)", styles):
    helpers += f"pub const {name}: GhosttyStyleFlags = 1 << {bit};\n"
helpers += '''pub const GHOSTTY_STYLE_UNDERLINE_MASK: GhosttyStyleFlags = 0x7 << GHOSTTY_STYLE_UNDERLINE_SHIFT;
pub const fn GHOSTTY_STYLE_UNDERLINE(style: GhosttyStyle) -> GhosttySgrUnderline {
    ((style.flags & GHOSTTY_STYLE_UNDERLINE_MASK) >> GHOSTTY_STYLE_UNDERLINE_SHIFT) as GhosttySgrUnderline
}
'''
(root / "src/helpers.rs").write_text(helpers)
subprocess.run(["rustfmt", "--edition", "2024", "src/bindings.rs", "src/helpers.rs"], cwd=root, check=True)
